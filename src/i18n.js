let currentLang = localStorage.getItem('maktab_crm_lang') || 'uz';

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (['uz', 'ru', 'en'].includes(lang)) {
    currentLang = lang;
  } else {
    currentLang = 'uz';
  }
  localStorage.setItem('maktab_crm_lang', currentLang);
  return currentLang;
}

export function t(key, fallback = '') {
  const dict = translations[currentLang] || translations.uz;
  if (dict && dict[key] !== undefined) {
    return dict[key];
  }
  if (translations.uz && translations.uz[key] !== undefined) {
    return translations.uz[key];
  }
  return fallback || key;
}

